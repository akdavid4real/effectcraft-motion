// ---- lookup -----------------------------------------------------------------
function findItem(name) {
  for (var i = 1; i <= app.project.numItems; i++) if (app.project.item(i).name == name) return app.project.item(i);
  return null;
}
function comp() {
  var c = findItem(COMP);
  if (!c) throw new Error("Comp '" + COMP + "' not found. Run s1 (it creates the comp) first.");
  return c;
}
function tr(layer, name) {
  return layer.property("ADBE Transform Group").property(name);
}

// ---- timing (needs timing.jsx, generated by `timeline.py emit`) -----------------
// SC("s3") -> {in, out, voiceAt, bg};  W("s3", "Halden") -> absolute time the word starts.
// nth: 1 = first occurrence. Throws if the word is missing, so typos fail loudly.
function SC(id) {
  if (typeof T === "undefined") throw new Error("timing.jsx not loaded; run timeline.py emit");
  var s = T.scenes[id];
  if (!s) throw new Error("No scene '" + id + "' in timeline");
  return s;
}
function W(id, word, nth) {
  if (typeof T === "undefined") throw new Error("timing.jsx not loaded; run timeline.py emit");
  var list = T.words[id];
  if (!list) throw new Error("No voice words for '" + id + "'");
  var key = String(word).toLowerCase().replace(/[^a-z0-9%.]/g, "");
  var hit = 0;
  for (var i = 0; i < list.length; i++) {
    if (list[i][0] == key) {
      hit++;
      if (hit == (nth || 1)) return list[i][1];
    }
  }
  throw new Error("Word '" + word + "' not found in voice line " + id);
}

// ---- lifetime -----------------------------------------------------------------
function life(layer, inT, outT) {
  layer.inPoint = inT;
  layer.outPoint = outT;
  return layer;
}
// Give every layer of a scene the scene's full span. Content must stay visible until
// the wipe covers it (S.out); fading out earlier creates empty frames (QA flags it).
function lifeAll(list, inT, outT) {
  for (var i = 0; i < list.length; i++) life(list[i], inT, outT);
}
// Remove a scene's layers so it can be rebuilt (in/out points snap to frames, hence 0.04).
function clearRange(c, a, b) {
  var n = 0;
  var removedSolids = [];
  for (var i = c.numLayers; i >= 1; i--) {
    var l = c.layer(i);
    if (/^soundtrack/i.test(l.name) || /^wipe/i.test(l.name)) continue;
    if (l.inPoint >= a - 0.04 && l.outPoint <= b + 0.04) {
      var source = null;
      try { source = l.source; } catch (e) {}
      var isSolid = source && source.mainSource && source.mainSource.color !== undefined;
      if (isSolid) removedSolids.push(source);
      l.remove();
      n++;
    }
  }
  // Each build creates new solid items (backgrounds, fades). Delete the ones no layer uses any
  // more, or every rebuild leaves another copy in the project file.
  for (var s = 0; s < removedSolids.length; s++) {
    try {
      if (removedSolids[s].usedIn.length == 0) removedSolids[s].remove();
    } catch (e) {}
  }
  return n;
}

// ---- keyframes ----------------------------------------------------------------
function easeAll(prop, influence) {
  var e = new KeyframeEase(0, influence || 75);
  for (var k = 1; k <= prop.numKeys; k++) {
    var tries = [[e], [e, e], [e, e, e]];
    for (var i = 0; i < tries.length; i++) {
      try {
        prop.setTemporalEaseAtKey(k, tries[i], tries[i]);
        break;
      } catch (err) {}
    }
  }
}
function keys(prop, list, influence) {
  for (var i = 0; i < list.length; i++) prop.setValueAtTime(list[i][0], list[i][1]);
  easeAll(prop, influence);
}

// ---- measuring ------------------------------------------------------------------
function rectOf(layer) {
  return layer.sourceRectAtTime(0, false);
}
function textWidth(l) {
  var r = rectOf(l);
  return r.left + r.width;
}
function centerAnchor(layer) {
  try {
    var r = rectOf(layer);
    tr(layer, "ADBE Anchor Point").setValue([r.left + r.width / 2, r.top + r.height / 2]);
  } catch (err) {}
}

// ---- builders -----------------------------------------------------------------
// Naming convention (QA relies on it): backgrounds start with "BG", wipes with "Wipe".
function bg(c, scene, dark) {
  var l = c.layers.addSolid(dark ? COL.dark : COL.light, "BG " + scene, W_, H_, 1);
  return l;
}
// Optional dot-grid texture (import a PNG named grid_light.png / grid_dark.png first).
function bgGrid(c, scene, dark) {
  var item = findItem(dark ? "grid_dark.png" : "grid_light.png");
  if (!item) return null;
  var l = c.layers.add(item);
  l.name = "BG grid " + scene;
  tr(l, "ADBE Scale").setValue([104, 104]);
  tr(l, "ADBE Position").expression = "value + [Math.sin(time * 0.25) * 6, (time * 6) % 30]";
  return l;
}

function rect(c, name, w, h, radius, color, pos, opts) {
  opts = opts || {};
  var l = c.layers.addShape();
  l.name = name;
  var g = l.property("ADBE Root Vectors Group").addProperty("ADBE Vector Group");
  var v = g.property("ADBE Vectors Group");
  var r = v.addProperty("ADBE Vector Shape - Rect");
  r.property("ADBE Vector Rect Size").setValue([w, h]);
  r.property("ADBE Vector Rect Roundness").setValue(radius);
  if (opts.stroke) {
    var s = v.addProperty("ADBE Vector Graphic - Stroke");
    s.property("ADBE Vector Stroke Color").setValue(opts.stroke);
    s.property("ADBE Vector Stroke Width").setValue(opts.strokeWidth || 2);
  }
  if (!opts.noFill) v.addProperty("ADBE Vector Graphic - Fill").property("ADBE Vector Fill Color").setValue(color);
  // leftAnchor: position = left-centre, so growX() grows rightwards
  if (opts.leftAnchor) g.property("ADBE Vector Transform Group").property("ADBE Vector Position").setValue([w / 2, 0]);
  tr(l, "ADBE Position").setValue(pos);
  if (opts.opacity !== undefined) tr(l, "ADBE Opacity").setValue(opts.opacity);
  return l;
}

function circle(c, name, d, color, pos, opts) {
  opts = opts || {};
  var l = c.layers.addShape();
  l.name = name;
  var v = l.property("ADBE Root Vectors Group").addProperty("ADBE Vector Group").property("ADBE Vectors Group");
  v.addProperty("ADBE Vector Shape - Ellipse").property("ADBE Vector Ellipse Size").setValue([d, d]);
  if (opts.stroke) {
    var s = v.addProperty("ADBE Vector Graphic - Stroke");
    s.property("ADBE Vector Stroke Color").setValue(opts.stroke);
    s.property("ADBE Vector Stroke Width").setValue(opts.strokeWidth || 2);
  }
  if (!opts.noFill) v.addProperty("ADBE Vector Graphic - Fill").property("ADBE Vector Fill Color").setValue(color);
  tr(l, "ADBE Position").setValue(pos);
  if (opts.opacity !== undefined) tr(l, "ADBE Opacity").setValue(opts.opacity);
  return l;
}

// Path in COMP coordinates (the layer is pinned at [0,0]; shape vertices are layer-relative).
function path(c, name, pts, color, width, opts) {
  opts = opts || {};
  var l = c.layers.addShape();
  l.name = name;
  tr(l, "ADBE Position").setValue([0, 0]);
  var v = l.property("ADBE Root Vectors Group").addProperty("ADBE Vector Group").property("ADBE Vectors Group");
  var s = new Shape();
  s.vertices = pts;
  var zero = [];
  for (var i = 0; i < pts.length; i++) zero.push([0, 0]);
  s.inTangents = opts.tin || zero;
  s.outTangents = opts.tout || zero;
  s.closed = !!opts.closed;
  v.addProperty("ADBE Vector Shape - Group").property("ADBE Vector Shape").setValue(s);
  if (opts.fill) {
    v.addProperty("ADBE Vector Graphic - Fill").property("ADBE Vector Fill Color").setValue(color);
  } else {
    var st = v.addProperty("ADBE Vector Graphic - Stroke");
    st.property("ADBE Vector Stroke Color").setValue(color);
    st.property("ADBE Vector Stroke Width").setValue(width || 2);
  }
  if (opts.opacity !== undefined) tr(l, "ADBE Opacity").setValue(opts.opacity);
  return l;
}

// Curved route between two points (quadratic arc lifted by lift * distance).
function arcGeom(a, b, lift) {
  var dist = Math.sqrt((b[0] - a[0]) * (b[0] - a[0]) + (b[1] - a[1]) * (b[1] - a[1]));
  var q = [(a[0] + b[0]) / 2, Math.min(a[1], b[1]) - dist * lift];
  return {
    a: a, b: b,
    c1: [a[0] + (2 / 3) * (q[0] - a[0]), a[1] + (2 / 3) * (q[1] - a[1])],
    c2: [b[0] + (2 / 3) * (q[0] - b[0]), b[1] + (2 / 3) * (q[1] - b[1])]
  };
}
function arc(c, name, geo, color, width, opts) {
  opts = opts || {};
  opts.tout = [[geo.c1[0] - geo.a[0], geo.c1[1] - geo.a[1]], [0, 0]];
  opts.tin = [[0, 0], [geo.c2[0] - geo.b[0], geo.c2[1] - geo.b[1]]];
  return path(c, name, [geo.a, geo.b], color, width, opts);
}
// Position expression that moves a layer along an arc forever (dashes are NOT supported).
function followArc(l, geo, speed, offset) {
  tr(l, "ADBE Position").expression =
    "var t=((time*" + (speed || 0.15) + ")+" + (offset || 0) + ")%1; var u=1-t;" +
    "var a=[" + geo.a + "],b=[" + geo.c1 + "],c=[" + geo.c2 + "],d=[" + geo.b + "];" +
    "a*(u*u*u)+b*(3*u*u*t)+c*(3*u*t*t)+d*(t*t*t)";
}
function trimOn(l, t0, t1) {
  var tp = l.property("ADBE Root Vectors Group").addProperty("ADBE Vector Filter - Trim");
  keys(tp.property("ADBE Vector Trim End"), [[t0, 0], [t1, 100]], 70);
  return tp;
}

// Text. opts: align 'left'|'center'|'right', tracking, name.
// Position = baseline-left for left text; centre of the text box for 'center'.
function txt(c, str, size, font, color, pos, opts) {
  opts = opts || {};
  var l = c.layers.addText(str);
  var td = l.property("ADBE Text Properties").property("ADBE Text Document");
  var doc = td.value;
  doc.font = font;
  doc.fontSize = size;
  doc.fillColor = color;
  doc.applyFill = true;
  doc.applyStroke = false;
  doc.tracking = opts.tracking === undefined ? (font == FONT.mono ? 60 : -25) : opts.tracking;
  var align = opts.align || "left";
  doc.justification =
    align == "center" ? ParagraphJustification.CENTER_JUSTIFY
      : align == "right" ? ParagraphJustification.RIGHT_JUSTIFY
      : ParagraphJustification.LEFT_JUSTIFY;
  td.setValue(doc);
  l.name = opts.name || str.slice(0, 28);
  tr(l, "ADBE Position").setValue(pos);
  if (align == "center") centerAnchor(l);
  return l;
}

// One line mixing fonts: [["Every mode.", FONT.head, COL.ink], ["One desk.", FONT.accent, COL.accent, 104]]
// (4th item = own size). opts.center = x to centre the whole line on.
function richLine(c, parts, x, y, size, opts) {
  opts = opts || {};
  var layers = [], cx = x, gap = size * (opts.gap || 0.24);
  for (var i = 0; i < parts.length; i++) {
    var p = parts[i];
    var l = txt(c, p[0], p[3] || size, p[1], p[2], [cx, y], {
      name: (opts.name || "line") + " " + i,
      tracking: p[1] == FONT.accent ? 0 : opts.tracking
    });
    cx += textWidth(l) + gap;
    layers.push(l);
  }
  if (opts.center) {
    var shift = opts.center - (cx - gap - x) / 2 - x;
    for (var j = 0; j < layers.length; j++) {
      var pp = tr(layers[j], "ADBE Position").value;
      tr(layers[j], "ADBE Position").setValue([pp[0] + shift, pp[1]]);
    }
  }
  return layers;
}

// Count-up number. Text-document expressions WORK in EffectCraft: use ONE layer, never
// a stack of hard-cut layers. Final value stays on screen until the layer's outPoint.
// countUp(layer, t0, t1, 99.4, 1, "%") -> "0.0%" … "99.4%"
function countUp(l, t0, t1, to, decimals, suffix) {
  l.property("ADBE Text Properties").property("ADBE Text Document").expression =
    "linear(time, " + t0 + ", " + t1 + ", 0, " + to + ").toFixed(" + (decimals || 0) + ") + '" + (suffix || "") + "'";
}

// Tinted icon from a white PNG (any size; displayed at sizePx).
function icon(c, itemName, color, pos, sizePx) {
  var item = findItem(itemName);
  if (!item) throw new Error("Icon '" + itemName + "' not imported");
  var l = c.layers.add(item);
  l.property("ADBE Effect Parade").addProperty("ADBE Fill").property("ADBE Fill-0002").setValue(color);
  var px = item.width || 512;
  var s = ((sizePx || 48) / px) * 100;
  tr(l, "ADBE Scale").setValue([s, s]);
  tr(l, "ADBE Position").setValue(pos);
  l.name = "icon " + itemName;
  return l;
}

function shadow(l, opacity, dist, soft) {
  var fx = l.property("ADBE Effect Parade").addProperty("ADBE Drop Shadow");
  try {
    fx.property("ADBE Drop Shadow-0001").setValue(COL.ink);
    fx.property("ADBE Drop Shadow-0002").setValue((opacity || 12) * 2.55);
    fx.property("ADBE Drop Shadow-0003").setValue(180);
    fx.property("ADBE Drop Shadow-0004").setValue(dist === undefined ? 16 : dist);
    fx.property("ADBE Drop Shadow-0005").setValue(soft || 46);
  } catch (err) {}
  return l;
}

// Parent BEFORE adding any scale-from-0 keys (pitfall: divide-by-zero makes children vanish).
function parent(children, p) {
  for (var i = 0; i < children.length; i++) children[i].parent = p;
}
// Put a decorative layer (ghost number, glow) UNDER another layer. New layers always go on
// top, so anything created after the headline covers it unless you move it.
function placeBelow(layer, target) {
  layer.moveAfter(target);
}

// Eyebrow label: small accent square + mono uppercase text.
function eyebrow(c, str, x, y, color) {
  var sq = rect(c, "Eyebrow dot " + str, 13, 13, 3, COL.accent, [x + 6.5, y - 9]);
  var t = txt(c, str, 24, FONT.mono, color || COL.ink2, [x + 28, y], { tracking: 120, name: "Eyebrow " + str });
  return [sq, t];
}

// Pill with optional dot. Returns { box, layers }; children are parented to box.
function pill(c, name, str, pos, bg, fg, opts) {
  opts = opts || {};
  var size = opts.size || 22, h = opts.h || size * 1.9;
  var t = txt(c, str, size, opts.font || FONT.head, fg, [0, 0], { name: name + " text", tracking: opts.tracking });
  var dotW = opts.dot === false ? 0 : size * 0.75;
  var w = textWidth(t) + dotW + size * 1.6;
  var box = rect(c, name, w, h, h / 2, bg, pos);
  t.moveBefore(box); // text was created first (to measure it): lift it above its background
  var left = pos[0] - w / 2 + size * 0.8, layers = [box];
  if (dotW) {
    layers.push(circle(c, name + " dot", size * 0.36, fg, [left + size * 0.18, pos[1]]));
    left += dotW;
  }
  tr(t, "ADBE Position").setValue([left, pos[1] + size * 0.36]);
  layers.push(t);
  parent(layers.slice(1), box);
  return { box: box, layers: layers, w: w };
}

// ---- animation presets ----------------------------------------------------------
function popIn(l, t, d, target) {
  d = d || 0.5;
  var s = target || tr(l, "ADBE Scale").value[0];
  keys(tr(l, "ADBE Scale"), [[t, [0, 0]], [t + d * 0.6, [s * 1.06, s * 1.06]], [t + d, [s, s]]], 65);
  keys(tr(l, "ADBE Opacity"), [[t, 0], [t + 0.12, 100]], 50);
}
// Fade + rise (the default text reveal).
function fadeUp(l, t, dy, d, toOpacity) {
  d = d || 0.7;
  dy = dy === undefined ? 36 : dy;
  var p = tr(l, "ADBE Position").value;
  keys(tr(l, "ADBE Position"), [[t, [p[0], p[1] + dy]], [t + d, [p[0], p[1]]]], 90);
  keys(tr(l, "ADBE Opacity"), [[t, 0], [t + d * 0.6, toOpacity === undefined ? 100 : toOpacity]], 60);
}
function fadeUpAll(list, t, stagger, dy, d) {
  for (var i = 0; i < list.length; i++) if (list[i].parent == null) fadeUp(list[i], t + i * (stagger || 0), dy, d);
}
function fadeIn(l, t, d, to) {
  keys(tr(l, "ADBE Opacity"), [[t, 0], [t + (d || 0.4), to === undefined ? 100 : to]], 60);
}
function fadeOut(l, t, d) {
  var o = tr(l, "ADBE Opacity").valueAtTime(t, false);
  keys(tr(l, "ADBE Opacity"), [[t, o], [t + (d || 0.35), 0]], 60);
}
function slideIn(l, t, dx, d) {
  d = d || 0.7;
  var p = tr(l, "ADBE Position").value;
  keys(tr(l, "ADBE Position"), [[t, [p[0] + dx, p[1]]], [t + d, [p[0], p[1]]]], 90);
  keys(tr(l, "ADBE Opacity"), [[t, 0], [t + d * 0.5, 100]], 60);
}
function growX(l, t, d) {
  keys(tr(l, "ADBE Scale"), [[t, [0, 100]], [t + (d || 0.7), [100, 100]]], 85);
}
function floaty(l, amp, speed, seed) {
  tr(l, "ADBE Position").expression = "value + [0, Math.sin(time * " + (speed || 1.2) + " + " + (seed || 0) + ") * " + (amp || 6) + "]";
}
function shake(l, t, amp, dur) {
  tr(l, "ADBE Position").expression =
    "var t0=" + t + ", d=" + (dur || 0.4) + "; (time > t0 && time < t0 + d) ? value + [Math.sin((time - t0) * 70) * " +
    (amp || 10) + " * (1 - (time - t0) / d), 0] : value";
}

// Two-tone wipe: accent band, then the next scene's colour. The frame is fully covered at
// t + 0.42, which is exactly when the next scene starts (timeline.py computes t = in - 0.42).
function wipe(c, t, colorB) {
  var a = rect(c, "Wipe A " + t, W_ + 20, H_ + 60, 0, COL.accent, [-W_ / 2, H_ / 2]);
  keys(tr(a, "ADBE Position"), [[t, [-W_ / 2, H_ / 2]], [t + 0.35, [W_ / 2, H_ / 2]], [t + 0.75, [W_ * 1.5, H_ / 2]]], 88);
  life(a, t, t + 0.8);
  var b = rect(c, "Wipe B " + t, W_ + 20, H_ + 60, 0, colorB, [-W_ / 2, H_ / 2]);
  keys(tr(b, "ADBE Position"), [[t + 0.07, [-W_ / 2, H_ / 2]], [t + 0.42, [W_ / 2, H_ / 2]], [t + 0.85, [W_ * 1.5, H_ / 2]]], 88);
  life(b, t + 0.07, t + 0.9);
  return [a, b];
}
